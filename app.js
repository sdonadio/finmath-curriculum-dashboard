  function boot() {
    var page = document.body.getAttribute("data-page");
    try {
      if (page === "index") renderIndex();
      else if (page === "course") renderCourse();
      else if (page === "concentration") renderConcentration();
      else if (page === "quarter") renderQuarter();
      else if (page === "skills") renderSkills();
      else fail("This page does not say which view it is.",
                "Its <body> needs a data-page attribute of index, course, concentration, quarter or skills.");
    } catch (err) {
      fail("This page could not be rendered.", err && err.message ? err.message : String(err));
    }
  }
  if (document.readyState === "loading") document.addEventListener("DOMContentLoaded", boot);
  else boot();
