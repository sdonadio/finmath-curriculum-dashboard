  /* SCHEMA.md declares `widget: {…} | null`, one per week. The shell also
     accepts an ARRAY of widget specs — a tolerated superset used only by
     tools/demo_course.js, which has to show all 13 types in five weeks. A
     real course file uses the single-object form. */
  function widgetsOf(W) {
    if (!W || !W.widget) return [];
    if (Object.prototype.toString.call(W.widget) === "[object Array]") {
      var out = [], i;
      for (i = 0; i < W.widget.length; i++) if (W.widget[i]) out.push(W.widget[i]);
      return out;
    }
    return [W.widget];
  }
