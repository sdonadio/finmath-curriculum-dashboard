  var LETTERS = "ABCDEFGH";
  function mcqKey(slug, weekN, i) { return "q:" + slug + ":" + weekN + ":" + i; }
  /* the per-week score line. The total lives on the node as data-total so the
     handler never has to be re-bound when a week is rebuilt. */
  function refreshScore(node, slug, weekN) {
    if (!node) return;
    var scan = store.scan("q:" + slug + ":" + weekN + ":"), k, right = 0, done = 0;
    var total = num(node.getAttribute("data-total"), 0);
    for (k in scan) if (has(scan, k)) { done++; if (rightFlag(scan[k])) right++; }
    node.textContent = done
      ? (right + " of " + total + " right, " + done + " attempted")
      : ("none of " + total + " answered yet");
  }
  function mcqCard(q, i, slug, weekN, scoreNode) {
    var box = el("div", "mcq");
    var key = mcqKey(slug, weekN, i);
    var answer = num(q.answer, -1);
    var opts = arr(q.options);
    var qp = add(box, el("p", "q"));
    add(qp, el("span", "qn", (i + 1) + "."));
    add(qp, document.createTextNode(trim(q.q)));
    var list = add(box, el("div", "opts"));
    var fb = el("div", "fb");
    var buttons = [], k, answered = false;

    function settle(chosen, store_it) {
      var right = chosen === answer, j;
      answered = true;
      for (j = 0; j < buttons.length; j++) {
        buttons[j].disabled = true;
        buttons[j].className = "opt " + (j === answer ? "right" : (j === chosen ? "wrong" : "dim"));
      }
      clear(fb);
      add(fb, el("b", null, right ? "Correct. " : "Not quite. "));
      if (!right && answer >= 0 && answer < opts.length) {
        add(fb, el("b", null, "The answer is " + LETTERS.charAt(answer) + ". "));
      }
      add(fb, document.createTextNode(trim(q.why)));
      fb.className = "fb show " + (right ? "good" : "poor");
      box.className = "mcq answered " + (right ? "right" : "wrong");
      if (store_it) store.set(key, (right ? "1" : "0") + ":" + chosen);
      refreshScore(scoreNode, slug, weekN);
    }

    for (k = 0; k < opts.length; k++) {
      (function (j) {
        var b = add(list, el("button", "opt"));
        b.type = "button";
        add(b, el("span", "ol", LETTERS.charAt(j)));
        add(b, document.createTextNode(trim(opts[j])));
        b.addEventListener("click", function () { if (!answered) settle(j, true); });
        buttons.push(b);
      }(k));
    }
    add(box, fb);
    /* replay a stored answer so a reload keeps the exact feedback */
    var prev = store.get(key);
    if (prev !== null && prev !== undefined && prev !== "") {
      var ch = chosenOf(prev);
      settle(ch >= 0 ? ch : (rightFlag(prev) ? answer : -1), false);
    }
    return box;
  }

