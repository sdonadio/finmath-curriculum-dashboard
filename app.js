  /* turn every course code inside a free-text string into a link */
  function linkifyCodes(host, text) {
    var s = txt(text), last = 0, m, rec, a;
    CODE_RE.lastIndex = 0;
    while ((m = CODE_RE.exec(s)) !== null) {
      rec = IDX[ckey(m[0])];
      if (m.index > last) add(host, document.createTextNode(s.slice(last, m.index)));
      if (rec && rec.written) { a = add(host, el("a", null, m[0])); a.href = courseHref(rec); }
      else add(host, el("b", null, m[0]));
      last = m.index + m[0].length;
    }
    if (last < s.length) add(host, document.createTextNode(s.slice(last)));
  }

