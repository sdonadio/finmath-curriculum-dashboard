  /* per-course progress, counted by scanning keys (no week index needed).
     An MCQ value is "<0|1>:<chosen index>": the leading flag says whether the
     answer was right, the index says what was clicked, so a reload replays the
     exact feedback the student saw rather than guessing a wrong option. */
  function rightFlag(v) { return txt(v).charAt(0) === "1"; }
  function chosenOf(v) { var p = txt(v).split(":"); return p.length > 1 ? num(p[1], -1) : -1; }
  function progressOf(slug) {
    var w = store.scan("w:" + slug + ":"), q = store.scan("q:" + slug + ":"), k;
    var weeks = 0, answered = 0, right = 0;
    for (k in w) if (has(w, k) && w[k] === "1") weeks++;
    for (k in q) if (has(q, k)) { answered++; if (rightFlag(q[k])) right++; }
    return { weeks: weeks, answered: answered, right: right };
  }

