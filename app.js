  function copyToClipboard(text, btn) {
    function done(ok) {
      btn.textContent = ok ? "copied" : "copy failed";
      btn.className = "btn tiny copy noprint" + (ok ? " ok" : "");
      window.setTimeout(function () { btn.textContent = "copy"; btn.className = "btn tiny copy noprint"; }, 1600);
    }
    function legacy() {
      try {
        var ta = document.createElement("textarea");
        ta.value = text; ta.setAttribute("readonly", "readonly");
        ta.style.position = "fixed"; ta.style.left = "-2000px"; ta.style.top = "0";
        document.body.appendChild(ta); ta.select();
        var ok = document.execCommand("copy");
        document.body.removeChild(ta);
        done(!!ok);
      } catch (e) { done(false); }
    }
    if (window.navigator && window.navigator.clipboard && window.navigator.clipboard.writeText) {
      try { window.navigator.clipboard.writeText(text).then(function () { done(true); }, legacy); return; }
      catch (e) { /* fall through */ }
    }
    legacy();
  }
